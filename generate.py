"""Original synthetic botanical artwork. Pillow raster paths; no external imagery.
Rebuild: python generate.py && ffmpeg command documented in README.md.
"""
from PIL import Image, ImageDraw, ImageFilter, PngImagePlugin
import math, random, os, shutil
W,H=1440,1000
os.makedirs('assets',exist_ok=True); os.makedirs('frames',exist_ok=True)
def mix(a,b,t):return tuple(round(x+(y-x)*t) for x,y in zip(a,b))
def smooth(a,b,t):
 t=max(0,min(1,(t-a)/(b-a))); return t*t*(3-2*t)
def bez(points,n=60):
 out=[]
 for i in range(n+1):
  t=i/n; u=1-t
  out.append((u**3*points[0][0]+3*u*u*t*points[1][0]+3*u*t*t*points[2][0]+t**3*points[3][0],u**3*points[0][1]+3*u*u*t*points[1][1]+3*u*t*t*points[2][1]+t**3*points[3][1]))
 return out
def shape(im,pts,top,bottom):
 mask=Image.new('L',(W,H));ImageDraw.Draw(mask).polygon(pts,fill=255)
 bounds=mask.getbbox()
 if not bounds:return
 x0,y0,x1,y1=bounds; grad=Image.new('RGB',(x1-x0,y1-y0)); d=ImageDraw.Draw(grad)
 for y in range(y1-y0):d.line((0,y,x1-x0,y),fill=mix(top,bottom,y/max(1,y1-y0-1)))
 im.paste(grad,(x0,y0),mask.crop(bounds))
def render(t):
 sky=smooth(.12,.75,t); im=Image.new('RGB',(W,H)); d=ImageDraw.Draw(im)
 for y in range(H):
  base=mix((25,27,23),(42,35,27),y/H)
  spring=mix((159,203,222),(220,232,220),y/750)
  d.line((0,y,W,y),fill=mix(base,spring,sky) if y<760 else mix((45,34,27),(24,24,20),(y-760)/240))
 # quiet dirt particles, fixed seed
 r=random.Random(44)
 for i in range(1200):
  x=r.randrange(W); y=r.randrange(775,H); size=r.choice([1,1,2,3]); c=r.choice([(65,47,34),(52,43,32),(74,55,39),(28,27,21)])
  d.ellipse((x,y,x+size*2,y+size),fill=c)
 # soil edge
 pts=[(0,H),(0,762)]+[(x,760+4*math.sin(x*.025)+2*math.sin(x*.087)) for x in range(0,W+4,4)]+[(W,H)]
 d.polygon(pts,fill=(38,31,24))
 for i in range(700):
  x=r.randrange(W); y=r.randrange(770,H); s=r.choice([1,2,3]);d.ellipse((x,y,x+s*2,y+s),fill=r.choice([(58,44,31),(49,39,29),(72,53,36)]))
 cx=920; by=820
 # roots
 roots=smooth(0,.35,t)
 for i in range(13):
  dx=(i-6)*20; path=bez([(cx+(i-6)*3,by+43),(cx+dx*.2,by+60),(cx+dx,by+80),(cx+dx*roots,by+43+120*roots)])
  d.line(path,fill=(166,143,96),width=2)
 # bulb body curved, layered copper tunic
 for j in range(11):
  width=57-j*3.1; top=by-94+j*3
  p=bez([(cx,top),(cx-width*.2,by-45),(cx-width*1.65,by+5),(cx-width*.55,by+38)])+bez([(cx-width*.55,by+38),(cx+width*1.4,by+78),(cx+width*1.4,by-19),(cx,top)])
  shape(im,p,mix((116,67,35),(201,150,88),j/11),(87+j*6,49+j*5,29+j*3))
 # stem, rising from bulb
 growth=smooth(.12,.73,t); topy=751-430*growth
 if growth>0:
  stem=bez([(cx-8,767),(cx-21,645),(cx+15,topy+120),(cx+1,topy)])+bez([(cx+13,topy),(cx+26,topy+120),(cx-3,650),(cx+8,767)])
  shape(im,stem,(95,135,58),(43,72,37))
 # long recurved lanceolate leaves
 leaf=smooth(.28,.78,t)
 for side,offset in ([(-1,0),(1,60)] if leaf>.001 else []):
  origin=(cx+side*2,752-offset*.2); tip=(cx+side*155*leaf,742-(280-offset)*leaf)
  p=bez([origin,(cx+side*25,690),(tip[0]-side*42,tip[1]+20),tip])+bez([tip,(tip[0]+side*65,tip[1]+150*leaf),(cx+side*46,751),origin])
  shape(im,p,(119,151,73) if side<0 else (85,126,65),(32,76,45))
  ImageDraw.Draw(im).line(bez([origin,(cx+side*35,680),(tip[0]-side*12,tip[1]+65),tip]),fill=(133,163,86),width=2)
 # petals: continuous bud -> six open satin petals
 bloom=smooth(.63,1,t); bud=smooth(.49,.69,t)
 if bud>0:
  base=(cx+8,topy+12); scale=bud; spread=30+110*bloom; height=(75+70*bloom)*scale
  # rear lobes then frontal cup
  for side,depth in [(-1,0),(1,0),(0,0),(-1,1),(1,1),(0,1)]:
   bx,byy=base; tipx=bx+side*spread*(1 if depth==0 else .7); tipy=byy-height*(1 if side else 1.24)+(22 if depth else -12)*bloom
   half=(32+36*bloom)*scale
   if side==0: half=(36+22*bloom)*scale
   p=bez([(bx,byy),(bx-half*1.3,byy-15),(tipx-half,tipy-40*scale),(tipx,tipy)])+bez([(tipx,tipy),(tipx+half,tipy-35*scale),(bx+half*1.4,byy-10),(bx,byy)])
   colors=[((248,161,139),(190,66,74)),((255,178,143),(201,76,83))]
   a,b=colors[depth]; shape(im,p,a,b)
   dr=ImageDraw.Draw(im)
   for k in range(-3,4):
    p=bez([(bx+k*2,byy-6),(bx+k*6,byy-45),(tipx+k*9,tipy+30),(tipx+k*5,tipy+8)])
    dr.line(p,fill=mix(a,b,.38+abs(k)*.08),width=1)
 return im
# reference is our own authored endpoint study, saved first before sequence
meta=PngImagePlugin.PngInfo();meta.add_text('Origin','Original synthetic artwork, generated by generate.py. No third-party image inputs.');meta.add_text('Prompt','Fixed soil cutaway. Copper tulip bulb grows roots, stem, leaves and open coral flower against spring sky.')
render(1).save('assets/reference.png',pnginfo=meta)
render(0).save('assets/start.png',pnginfo=meta);render(1).save('assets/end.png',pnginfo=meta)
for i in range(121):
 im=render(i/120); im.save(f'frames/{i:04d}.png')
 if i in (0,40,80,120):im.resize((720,500)).save(f'assets/stage-{i//40}.webp',quality=90)
print('Rendered START, END, reference and 121 transition frames.')
